"""Pull a Probe-ability release and regenerate everything the daemon's port is built from.

    python tools/update.py              # latest tag
    python tools/update.py --ref v0.12.0

Writes two files and touches nothing else:
  src/ProbeAbility/ProbeAbilityModel.g.cs              the model blob, tables and encodings
  tests/ProbeAbility.Tests/ProbeAbilityGolden.json     vectors scored by *their* Python

Then run the tests: they score the golden vectors through the C# port and fail on any difference, so a
release that changed the feature code (not just the trees) shows up red rather than as quietly worse
predictions. Probe-ability is MIT, (c) Tim Snels; the generated file carries the licence.
"""

import argparse
import base64
import os
import subprocess
import sys
import tempfile

REPO_URL = "https://github.com/snelstim/Probe-ability"
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, ".."))
OUT_CS = os.path.join(ROOT, "src", "ProbeAbility", "ProbeAbilityModel.g.cs")
OUT_GOLDEN = os.path.join(ROOT, "tests", "ProbeAbility.Tests", "ProbeAbilityGolden.json")


def git(*args, cwd=None):
    return subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True, text=True).stdout.strip()


def latest_tag():
    lines = git("ls-remote", "--tags", "--refs", REPO_URL).splitlines()
    tags = [line.split("refs/tags/")[1] for line in lines]

    def key(tag):
        return tuple(int(p) if p.isdigit() else 0 for p in tag.lstrip("v").split("."))

    return max(tags, key=key)


def cs_string(value):
    return '"' + value.replace("\\", "\\\\").replace('"', '\\"') + '"'


def cs_double(value):
    text = repr(float(value))
    return text if any(c in text for c in ".eE") else text + ".0"


def codes(t):
    return "(" + ", ".join(str(int(v)) for v in t) + ")"


def generate(pkg, source):
    sys.path.insert(0, pkg)
    import ml_model_code as m
    import ml_predictor as mp

    blob = m._DATA if isinstance(m._DATA, (bytes, bytearray)) else base64.b64decode(m._DATA)
    indent = "\n        "

    def offsets(rows):
        return ("," + indent).join(f"({s}, {c})" for s, c in rows)

    cook_names = indent.join(f"[{cs_string(k)}] = {codes(v)}," for k, v in mp._COOK_NAME_MAP.items())
    cut_names = []
    for name, (cut_id, doneness) in mp._CUT_NAME_MAP.items():
        options = ", ".join(f"({cs_double(t)}, {codes(mp._encode(cut_id, d))})" for d, t in doneness)
        cut_names.append(f"[{cs_string(name)}] = [{options}],")
    presets = []
    for name, (cut_id, doneness) in mp._CUT_NAME_MAP.items():
        for don, temp in doneness:
            full = f"{name} {don.replace('_', ' ').title()}"
            if full in mp._COOK_NAME_MAP:
                presets.append(f"({cs_string(full)}, {cs_double(temp)}),")
    untargeted = indent.join(f"[{cs_string(n)}] = {codes(mp._encode(c, 'medium'))}," for n, (c, _) in mp._CUT_NAME_MAP.items())
    categories = []
    for name, cut_id in mp._CATEGORY_NAME_MAP.items():
        cat, ani, _, _ = mp._CUT_LOOKUP.get(cut_id, mp._CUT_LOOKUP["other"])
        generic = (cat, ani, mp._CUT_TYPE_ENC["other"], mp._CUT_ENC["other"], mp._DONENESS_ENC["medium"])
        categories.append(f"[{cs_string(name)}] = {codes(generic)},")

    with open(os.path.join(pkg, "..", "..", "LICENSE"), encoding="utf-8") as fh:
        licence = fh.read().strip()
    header = "\n".join("// " + line if line else "//" for line in licence.splitlines())

    text = f"""// <auto-generated>
// Generated by tools/update.py from {source}.
// Do not edit by hand: re-run the script, then the tests.
//
// Probe-ability's cook-time model, ported. Original licence follows.
//
{header}
// </auto-generated>

namespace ProbeAbility;

public static partial class ProbeAbilityModel
{{
    public const string Source = {cs_string(source)};

    private const double Init = {cs_double(m._INIT)};
    private const double LearningRate = {cs_double(m._LR)};
    private static readonly bool LogTarget = {str(bool(getattr(m, "_LOG", False))).lower()};
    private static readonly bool Blend = {str(bool(getattr(m, "_BLEND", False))).lower()};
    private const double InitFar = {cs_double(getattr(m, "_INIT_FAR", 0.0))};
    private const double LearningRateFar = {cs_double(getattr(m, "_LR_FAR", 0.0))};
    private const double RemainingFar = {cs_double(getattr(m, "_T_FAR", 0.0))};
    private const double RemainingNear = {cs_double(getattr(m, "_T_NEAR", 0.0))};
    private const int RemainingFeature = {int(getattr(m, "_I_TREM", 6))};
    private const int NodeSize = {int(m._NS)};

    private static readonly (int Start, int Count)[] Trees =
    [
        {offsets(m._OFFSETS)}
    ];

    private static readonly (int Start, int Count)[] TreesFar =
    [
        {offsets(getattr(m, "_OFFSETS_FAR", ()))}
    ];

    private static readonly byte[] Nodes = System.Convert.FromBase64String(
        {cs_string(base64.b64encode(blob).decode("ascii"))});

    /// <summary>Full preset names ("Beef Brisket Fall Apart") to the model's five category codes.</summary>
    private static readonly Dictionary<string, (int, int, int, int, int)> CookNames = new()
    {{
        {cook_names}
    }};

    /// <summary>"Category Cut" to (doneness temperature, codes); the doneness nearest the target wins.</summary>
    private static readonly Dictionary<string, (double Celsius, (int, int, int, int, int) Codes)[]> CutNames = new()
    {{
        {indent.join(cut_names)}
    }};

    /// <summary>"Category Cut" with no target to go on: that cut, at doneness "medium".</summary>
    private static readonly Dictionary<string, (int, int, int, int, int)> CutNamesUntargeted = new()
    {{
        {untargeted}
    }};

    /// <summary>A bare category ("Beef") to a generic cut's codes.</summary>
    private static readonly Dictionary<string, (int, int, int, int, int)> CategoryNames = new()
    {{
        {indent.join(categories)}
    }};

    private static readonly (int, int, int, int, int) DefaultMeat = {codes(mp._DEFAULT_MEAT)};

    /// <summary>
    /// Every preset Probe-ability offers, as the name the model knows it by and its target in Celsius -
    /// for a picker whose choice both sets a probe's target and tells the model what is cooking.
    /// </summary>
    public static readonly IReadOnlyList<(string Name, double Celsius)> Presets =
    [
        {indent.join(presets)}
    ];

    /// <summary>The trained column order; <see cref="Features"/> fills it in this order.</summary>
    public static readonly string[] FeatureOrder = [{", ".join(cs_string(f) for f in mp._FEATURE_ORDER)}];
}}
"""
    os.makedirs(os.path.dirname(OUT_CS), exist_ok=True)
    with open(OUT_CS, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--ref", help="tag or commit (default: the latest tag)")
    ref = parser.parse_args().ref or latest_tag()

    with tempfile.TemporaryDirectory() as tmp:
        checkout = os.path.join(tmp, "repo")
        git("clone", "--quiet", "--depth", "1", "--branch", ref, REPO_URL, checkout)
        source = f"{REPO_URL} {ref} ({git('rev-parse', '--short', 'HEAD', cwd=checkout)})"
        pkg = os.path.join(checkout, "custom_components", "probe_ability")

        generate(pkg, source)
        env = dict(os.environ, PROBEABILITY_PKG=pkg, PROBEABILITY_SOURCE=source, PROBEABILITY_GOLDEN=OUT_GOLDEN)
        subprocess.run([sys.executable, os.path.join(HERE, "make_golden.py")],
                       check=True, env=env, stdout=subprocess.DEVNULL)

    print(f"Regenerated from {source}:")
    print(f"  {os.path.relpath(OUT_CS, ROOT)}")
    print(f"  {os.path.relpath(OUT_GOLDEN, ROOT)}")
    print("Now: dotnet test")


if __name__ == "__main__":
    main()
